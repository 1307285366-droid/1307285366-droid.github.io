  var FALLBACK = '这个问题我暂时答不上来。你可以点下面的常见问题，或者去「我的 → 设置」看看说明。';

  var COMMON = ['怎么开始刷题？', '错题本怎么用？', '为什么有的题显示“本题不计分”？', '怎么注册账号？为什么要注册？', '我的进度存在哪里？换台电脑还有吗？'];

  /** 用关键词匹配一条最合适的回答 */
  function ask(text) {
    var input = String(text || '').trim();
    if (!input) return { q: '', a: '你想问点什么？' };

    var best = null;
    var bestScore = 0;
    FAQ.forEach(function (item) {
      var score = 0;
      item.keys.forEach(function (k) { if (input.indexOf(k) >= 0) score += k.length; });
      if (input.indexOf(item.q.slice(0, 4)) >= 0) score += 3;
      if (score > bestScore) { bestScore = score; best = item; }
    });
    return { q: input, a: best ? best.a : FALLBACK, matched: Boolean(best) };
  }

  function byQuestion(question) {
    var hit = FAQ.filter(function (item) { return item.q === question; })[0];
    return hit || { q: question, a: FALLBACK };
  }

  global.Support = {
    faq: FAQ,
    common: COMMON,
    ask: ask,
    byQuestion: byQuestion,
    fallback: FALLBACK,
  };
